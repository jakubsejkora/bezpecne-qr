#!/usr/bin/env node
// Validates the shared corpus + rules and bundles them for the HTML prototype.
//   node scripts/gen-prototype-data.mjs
// Output: prototype/data/data.js  (window.BQ_DATA = {...}; works from file:// without a server)
// Exits non-zero if any sample disagrees with the reference engine or references unknown IDs.

import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { assess } from './lib/engine.mjs';
import { isValidIBAN, czIBANToDomestic } from './lib/banking.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const readJSON = async (p) => JSON.parse(await readFile(path.join(root, p), 'utf8'));

const [corpus, weights, signals, banks, operatorGuide, recoveryGuide, parking, version] = await Promise.all([
  readJSON('shared/testdata/samples.json'),
  readJSON('shared/rules/weights.json'),
  readJSON('shared/rules/signals.json'),
  readJSON('shared/rules/bank-codes-cz.json'),
  readJSON('shared/content/operator-guide.json'),
  readJSON('shared/content/recovery-guide.json'),
  readJSON('shared/rules/parking.json'),
  readFile(path.join(root, 'VERSION'), 'utf8').then((s) => s.trim()),
]);

const errors = [];
const ids = new Set();

for (const s of corpus.samples) {
  const where = `sample ${s.id}`;
  if (ids.has(s.id)) errors.push(`${where}: duplicate id`);
  ids.add(s.id);
  for (const k of ['group', 'scene', 'symbology', 'payload', 'type', 'engine', 'title', 'expected']) {
    if (s[k] === undefined) errors.push(`${where}: missing ${k}`);
  }
  for (const sig of s.signals || []) if (!signals.evidence[sig.id]) errors.push(`${where}: no texts for evidence ${sig.id}`);
  for (const c of s.consequences || []) if (!signals.consequences[c.id]) errors.push(`${where}: unknown consequence ${c.id}`);
  for (const c of s.checks || []) if (!signals.checks[c.id]) errors.push(`${where}: unknown check ${c.id}`);
  const reason = s.completeness?.reason;
  if (reason && reason.startsWith('inc.') && !signals.incomplete[reason]) errors.push(`${where}: unknown incomplete reason ${reason}`);

  // Payment data must be internally consistent with the reference validators.
  const f = s.fields || {};
  if (f.iban) {
    const valid = isValidIBAN(f.iban);
    const expectInvalid = s.id === 'spd-invalid-iban';
    if (valid === expectInvalid) errors.push(`${where}: IBAN validity ${valid} contradicts expectation`);
    if (!s.payload.includes(f.iban)) errors.push(`${where}: IBAN not present in payload`);
    const dom = czIBANToDomestic(f.iban);
    if (dom && f.domestic && dom.domestic !== f.domestic) errors.push(`${where}: domestic ${f.domestic} ≠ ${dom.domestic}`);
    if (dom && !banks.banks[dom.bankCode]) errors.push(`${where}: unknown bank code ${dom.bankCode}`);
    if (dom) f.bankName = banks.banks[dom.bankCode]?.name || null;
  }

  try {
    const result = assess(weights, s);
    s.assessment = result;
    if (result.band !== s.expected.band) errors.push(`${where}: engine band ${result.band} (score ${result.score}) ≠ expected ${s.expected.band}`);
  } catch (e) {
    errors.push(`${where}: ${e.message}`);
  }
}

for (const sc of corpus.scenarios || []) {
  for (const child of sc.children) if (!ids.has(child)) errors.push(`scenario ${sc.id}: unknown child ${child}`);
}

if (errors.length) {
  console.error(`✗ ${errors.length} problem(s):\n  - ` + errors.join('\n  - '));
  process.exit(1);
}

const data = {
  version,
  samples: corpus.samples,
  scenarios: corpus.scenarios || [],
  signals,
  weights,
  banks: banks.banks,
  operatorGuide,
  recoveryGuide,
  parking,
};

await mkdir(path.join(root, 'prototype/data'), { recursive: true });
await writeFile(
  path.join(root, 'prototype/data/data.js'),
  `// Generated by scripts/gen-prototype-data.mjs from shared/ — do not edit.\nwindow.BQ_DATA = ${JSON.stringify(data)};\n`,
);

const tally = corpus.samples.reduce((m, s) => ((m[s.assessment.band] = (m[s.assessment.band] || 0) + 1), m), {});
console.log(`✓ ${corpus.samples.length} samples valid (${Object.entries(tally).map(([k, v]) => `${k} ${v}`).join(', ')}) → prototype/data/data.js`);
